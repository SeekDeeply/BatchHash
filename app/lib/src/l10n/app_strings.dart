  /// Locale used when the platform does not request a supported language.
  static const String defaultLocale = 'zh';

  /// Languages the UI currently ships.
  static const List<String> supportedLocales = <String>['zh', 'en'];

  static const Map<String, Map<String, String>> _tables =
      <String, Map<String, String>>{'zh': _zh, 'en': _en};

  /// Resolve a key for a locale, falling back to Chinese and then to the key.
  static String of(String key, {String? locale, Map<String, String>? args}) {
    final String language = _language(locale);
    String? template =
        _tables[language]?[key] ?? _tables[defaultLocale]?[key] ?? key;
    if (args != null) {
      for (final String name in args.keys) {
        template = template!.replaceAll('{' + name + '}', args[name]!);
      }
    }
    return template!;
  }

  /// Normalize a locale code to one of [supportedLocales].
  ///
  /// Unknown or empty codes fall back to [defaultLocale], which is why the
  /// application is Chinese-first even on an unsupported platform language.
  static String normalize(String? locale) => _language(locale);

  static String _language(String? locale) {
    if (locale == null || locale.isEmpty) {
      return defaultLocale;
    }
    final String lower = locale.toLowerCase();
    if (lower.startsWith('en')) {
      return 'en';
    }
    if (lower.startsWith('zh')) {
      return 'zh';
    }
    return defaultLocale;
  }

